"""Deterministic rendering of the parity-checked catalog into the agent variant.

Each variant page is served at the same path as the original page, as semantic HTML
(default) or Markdown (`Accept: text/markdown` or a `.md` path), with JSON-LD. No model
writes page text: everything here comes from the validated catalog.
"""

import html
import json
from dataclasses import dataclass
from datetime import datetime

from app.engines.variants.contracts import Catalog, Product

ACTIONS = [
    ("search_products", "GET /agent-api/search?q=&size=&max_price=", "Find products."),
    ("get_product", "GET /agent-api/products/{slug}", "Price, sizes and availability."),
    ("check_delivery", "GET /agent-api/delivery?pin=", "Delivery estimate for a PIN code."),
]


@dataclass
class VariantPageContent:
    path: str
    markdown: str
    html: str


def markdown_path(path: str) -> str:
    return "/index.md" if path in ("", "/") else path.rstrip("/") + ".md"


def _money(value: float, currency: str) -> str:
    symbol = {"INR": "₹", "USD": "$", "EUR": "€", "GBP": "£"}.get(currency, currency + " ")
    amount = f"{value:,.0f}" if float(value).is_integer() else f"{value:,.2f}"
    return symbol + amount


def _clean(value: str | None) -> str:
    return " ".join((value or "").split())


def _availability(product: Product) -> str | None:
    known = [size.in_stock for size in product.sizes if size.in_stock is not None]
    if not known:
        return None
    return "https://schema.org/InStock" if any(known) else "https://schema.org/OutOfStock"


def _in_stock_sizes(product: Product) -> list[str]:
    return [size.size for size in product.sizes if size.in_stock]


def _footer(generated_at: datetime) -> str:
    return (
        f"Generated by AgentLane from the public site on {generated_at:%d %b %Y %H:%M} UTC. "
        "Prices and availability are as of that time; the store's checkout is authoritative."
    )


def _html_page(title: str, body: str, jsonld: dict, md_href: str) -> str:
    return (
        '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
        f"<title>{html.escape(title)}</title>"
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f'<link rel="alternate" type="text/markdown" href="{html.escape(md_href)}">'
        '<script type="application/ld+json">'
        + json.dumps(jsonld, ensure_ascii=False).replace("</", "<\\/")
        + "</script></head><body>"
        + body
        + "</body></html>\n"
    )


def _actions_markdown() -> str:
    lines = ["## Agent actions", ""]
    lines += [f"- `{name}`: `{call}`. {text}" for name, call, text in ACTIONS]
    lines += ["- MCP: `POST /mcp` (Streamable HTTP) exposes the same three tools.", ""]
    return "\n".join(lines)


def _actions_html() -> str:
    items = "".join(
        f"<li><code>{name}</code>: <code>{html.escape(call)}</code>. {html.escape(text)}</li>"
        for name, call, text in ACTIONS
    )
    return (
        "<section><h2>Agent actions</h2><ul>"
        + items
        + "<li>MCP: <code>POST /mcp</code> exposes the same three tools.</li></ul></section>"
    )


def _home(catalog: Catalog, generated_at: datetime) -> VariantPageContent:
    c = catalog.currency
    md = [f"# {_clean(catalog.store_name)}", "", _clean(catalog.summary), "", "## Products", ""]
    items_html = []
    for p in catalog.products:
        sizes = _in_stock_sizes(p)
        stock = f" · in stock: {', '.join(sizes)}" if sizes else ""
        md.append(f"- [{_clean(p.name)}]({p.path}): {_money(p.price, c)}{stock}")
        items_html.append(
            f'<li><a href="{html.escape(p.path)}">{html.escape(_clean(p.name))}</a>: '
            f"{html.escape(_money(p.price, c))}{html.escape(stock)}</li>"
        )
    if catalog.policies:
        md += ["", "## Policies", ""]
        md += [f"- **{_clean(x.topic)}**: {_clean(x.text)}" for x in catalog.policies]
    if catalog.key_tasks:
        md += ["", "## What you can do here", ""]
        md += [f"- {_clean(t.name)}: {_clean(t.description)}" for t in catalog.key_tasks]
    md += ["", _actions_markdown(), f"_{_footer(generated_at)}_", ""]
    policies_html = "".join(
        f"<li><strong>{html.escape(_clean(x.topic))}</strong>: {html.escape(_clean(x.text))}</li>"
        for x in catalog.policies
    )
    body = (
        f"<main><h1>{html.escape(_clean(catalog.store_name))}</h1>"
        f"<p>{html.escape(_clean(catalog.summary))}</p>"
        f"<section><h2>Products</h2><ul>{''.join(items_html)}</ul></section>"
        + (f"<section><h2>Policies</h2><ul>{policies_html}</ul></section>" if policies_html else "")
        + _actions_html()
        + f"<footer><p>{html.escape(_footer(generated_at))}</p></footer></main>"
    )
    jsonld = {
        "@context": "https://schema.org",
        "@type": "Store",
        "name": _clean(catalog.store_name),
        "description": _clean(catalog.summary),
        "currenciesAccepted": c,
        "hasOfferCatalog": {
            "@type": "OfferCatalog",
            "name": "Products",
            "itemListElement": [
                {
                    "@type": "Offer",
                    "itemOffered": {"@type": "Product", "name": _clean(p.name)},
                    "price": p.price,
                    "priceCurrency": c,
                    "url": p.path,
                }
                for p in catalog.products
            ],
        },
    }
    return VariantPageContent(
        "/", "\n".join(md), _html_page(catalog.store_name, body, jsonld, "/index.md")
    )


def _product(catalog: Catalog, p: Product, generated_at: datetime) -> VariantPageContent:
    c = catalog.currency
    rows = [
        (s.size, "In stock" if s.in_stock else "Out of stock" if s.in_stock is False else "Unknown")
        for s in p.sizes
    ]
    md = [f"# {_clean(p.name)}", "", f"**Price:** {_money(p.price, c)}"]
    if p.category:
        md.append(f"**Category:** {_clean(p.category)}")
    if p.description:
        md += ["", _clean(p.description)]
    if rows:
        md += ["", "## Sizes", "", "| Size | Availability |", "| --- | --- |"]
        md += [f"| {size} | {state} |" for size, state in rows]
    md += [
        "",
        (
            f"Check live price and sizes: `GET /agent-api/products/{p.slug}`. "
            "Delivery estimate: `GET /agent-api/delivery?pin=`."
        ),
        "",
        f"[All products](/) · _{_footer(generated_at)}_",
        "",
    ]
    table = "".join(
        f"<tr><td>{html.escape(size)}</td><td>{state}</td></tr>" for size, state in rows
    )
    body = (
        f'<main><nav><a href="/">All products</a></nav><h1>{html.escape(_clean(p.name))}</h1>'
        f"<p><strong>Price:</strong> {html.escape(_money(p.price, c))}</p>"
        + (
            f"<p><strong>Category:</strong> {html.escape(_clean(p.category))}</p>"
            if p.category
            else ""
        )
        + (f"<p>{html.escape(_clean(p.description))}</p>" if p.description else "")
        + (
            '<section><h2>Sizes</h2><table><thead><tr><th scope="col">Size</th>'
            f'<th scope="col">Availability</th></tr></thead><tbody>{table}</tbody></table></section>'
            if rows
            else ""
        )
        + f"<p>Live data: <code>GET /agent-api/products/{html.escape(p.slug)}</code></p>"
        + f"<footer><p>{html.escape(_footer(generated_at))}</p></footer></main>"
    )
    offer = {"@type": "Offer", "price": p.price, "priceCurrency": c, "url": p.path}
    if availability := _availability(p):
        offer["availability"] = availability
    jsonld = {
        "@context": "https://schema.org",
        "@type": "Product",
        "name": _clean(p.name),
        "sku": p.slug,
        **({"description": _clean(p.description)} if p.description else {}),
        **({"category": _clean(p.category)} if p.category else {}),
        "offers": offer,
    }
    return VariantPageContent(
        p.path, "\n".join(md), _html_page(p.name, body, jsonld, markdown_path(p.path))
    )


def _llms_txt(catalog: Catalog) -> str:
    c = catalog.currency
    lines = [
        f"# {_clean(catalog.store_name)}",
        "",
        f"> {_clean(catalog.summary)}",
        "",
        "## Products",
        "",
    ]
    lines += [
        f"- [{_clean(p.name)}]({markdown_path(p.path)}): {_money(p.price, c)}"
        for p in catalog.products
    ]
    lines += ["", "## Agent actions", ""]
    lines += [
        f"- [{name}]({call.split(' ')[1].split('?')[0]}): {text}" for name, call, text in ACTIONS
    ]
    lines += ["- [MCP server](/mcp): the same tools over Streamable HTTP", ""]
    return "\n".join(lines)


def render_variant(
    catalog: Catalog, generated_at: datetime
) -> tuple[list[VariantPageContent], str]:
    """Returns the variant pages and the llms.txt body."""
    pages = [_home(catalog, generated_at)]
    seen = {"/"}
    for product in catalog.products:
        if product.path.startswith("/") and product.path not in seen:
            seen.add(product.path)
            pages.append(_product(catalog, product, generated_at))
    return pages, _llms_txt(catalog)
